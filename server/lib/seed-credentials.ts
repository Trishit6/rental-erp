/**
 * Resolves the passwords the development seeders hash into the database.
 *
 * ## Why this exists at all
 *
 * The seeded admin and demo passwords used to be string literals in source. That
 * published a working credential to anyone who cloned the repository, and it made
 * rotating the password require editing the very scripts that TRUNCATE every table.
 *
 * ## What it does instead
 *
 * `ADMIN_PASSWORD` (the admin account) and `DEMO_PASSWORD` (every other shared demo
 * account) are read from the environment. When neither the environment nor a
 * previously generated credentials file supplies a value, a random password is
 * generated **once** and written to `.seed-credentials.local` (gitignored, mode
 * `0600`). Later seed stages — and later runs — read that file back, so the volume
 * accounts seeded by `seed-history.ts` share the same password as the demo accounts
 * without the value ever living in the repository.
 *
 * The generated file is a local development artefact: it is never read at request
 * time, and production never runs these scripts (`NODE_ENV=production` is refused).
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export type SeedCredentials = {
  /** Admin login. `ADMIN_EMAIL` when set, otherwise the documented local default. */
  adminEmail: string;
  /** Password for the admin account. */
  adminPassword: string;
  /** Shared password for every other seeded demo/volume account. */
  demoPassword: string;
  /** Location of the generated-credentials file (whether or not it was written). */
  file: string;
  /** True when a value was generated and persisted because the environment had none. */
  generated: boolean;
};

/** Unambiguous, shell-safe random password: 24 bytes of entropy as 48 hex characters. */
function randomPassword(): string {
  return randomBytes(24).toString("hex");
}

function credentialsFilePath(): string {
  const override = process.env.SEED_CREDENTIALS_FILE?.trim();
  return override || join(process.cwd(), ".seed-credentials.local");
}

/** Parse the small `KEY=VALUE` file we write. Unknown or malformed lines are ignored. */
function readCredentialsFile(file: string): Record<string, string> {
  if (!existsSync(file)) return {};
  const values: Record<string, string> = {};
  for (const rawLine of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = /^([A-Z_][A-Z0-9_]*)=(.*)$/.exec(line);
    if (match) values[match[1]!] = match[2]!;
  }
  return values;
}

/**
 * Resolve the seed credentials, generating and persisting a random password on the
 * first run that does not have one configured.
 *
 * Precedence per value: environment → previously generated file → (generate).
 * `DEMO_PASSWORD` falls back to the admin password, matching the long-standing
 * behaviour where the demo accounts and the admin shared one value unless separated.
 */
export function resolveSeedCredentials(options?: { file?: string }): SeedCredentials {
  const file = options?.file ?? credentialsFilePath();
  const fromFile = readCredentialsFile(file);

  const adminEmail =
    process.env.ADMIN_EMAIL?.trim() || fromFile.ADMIN_EMAIL || "admin@revaro.local";

  const suppliedAdmin = process.env.ADMIN_PASSWORD?.trim() || fromFile.ADMIN_PASSWORD;
  const suppliedDemo = process.env.DEMO_PASSWORD?.trim() || fromFile.DEMO_PASSWORD;

  const generated = !suppliedAdmin;
  const adminPassword = suppliedAdmin || randomPassword();
  const demoPassword = suppliedDemo || adminPassword;

  if (generated) {
    writeFileSync(
      file,
      [
        "# Generated by the Revaro development seeders. Gitignored — do not commit.",
        "# Delete this file and re-run `pnpm db:seed` to rotate the demo passwords.",
        `ADMIN_EMAIL=${adminEmail}`,
        `ADMIN_PASSWORD=${adminPassword}`,
        `DEMO_PASSWORD=${demoPassword}`,
        "",
      ].join("\n"),
      { mode: 0o600 },
    );
  }

  return { adminEmail, adminPassword, demoPassword, file, generated };
}
